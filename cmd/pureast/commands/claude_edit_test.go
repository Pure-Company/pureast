func TestWriteWithHeader_NonGoTarget(t *testing.T) {
	dir := t.TempDir()
	makefilePath := filepath.Join(dir, "Makefile")

	body := "build:\n\tgo build ./...\n"
	if err := writeWithHeader(makefilePath, "build the project", "v1:hash123", body); err != nil {
		t.Fatal(err)
	}

	contents, _ := os.ReadFile(makefilePath)
	s := string(contents)

	// Header must use # comments (Makefile syntax), not //
	if !strings.HasPrefix(s, "# Code generated") {
		t.Errorf("Makefile header should start with '# Code generated'; got:\n%s", s)
	}
	if strings.Contains(s, "// pureast-cache-key") {
		t.Errorf("Makefile must not contain Go-style cache-key line")
	}
	if !strings.Contains(s, "# pureast-cache-key: v1:hash123") {
		t.Errorf("Makefile missing # pureast-cache-key header line; got:\n%s", s)
	}
	if !strings.Contains(s, "build:\n\tgo build") {
		t.Errorf("Makefile body missing; got:\n%s", s)
	}

	// Verify readCachedKey can read back the # prefix.
	key, ok := readCachedKey(makefilePath)
	if !ok || key != "v1:hash123" {
		t.Errorf("readCachedKey on Makefile = (%q, %v), want (v1:hash123, true)", key, ok)
	}
}

func TestLooksLikeContent_NonGo(t *testing.T) {
	cases := []struct {
		in   string
		want bool
	}{
		{"build:\n\tgo build", true},                   // Makefile content
		{"FROM golang:1.22\nCOPY . .", true},           // Dockerfile content
		{"version: '3'\nservices:\n  app: {}", true},   // compose
		{"# build the thing\nbuild:", true},            // comment-leading
		{"## Summary\nThis Makefile builds...", false}, // markdown summary
		{"Here is the Makefile:\n\nbuild:", false},     // prose preamble
		{"I've created a Dockerfile that...", false},   // prose preamble
		{"", false}, // empty
	}
	for _, c := range cases {
		if got := looksLikeContent(c.in, false); got != c.want {
			t.Errorf("looksLikeContent(%q, false) = %v, want %v", c.in, got, c.want)
		}
	}
}
