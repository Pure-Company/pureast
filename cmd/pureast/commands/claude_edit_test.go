func TestComputeCacheKey_DeterministicAndSensitive(t *testing.T) {
	// Same inputs produce same key.
	a := computeCacheKey("task A", "context X")
	a2 := computeCacheKey("task A", "context X")
	if a != a2 {
		t.Fatalf("same inputs -> different keys: %q vs %q", a, a2)
	}

	// Task change -> different key.
	if computeCacheKey("task B", "context X") == a {
		t.Errorf("task change should change key")
	}

	// Context change -> different key.
	if computeCacheKey("task A", "context Y") == a {
		t.Errorf("context change should change key")
	}

	// Hash format: starts with cache-version prefix.
	if !strings.HasPrefix(a, cacheVersion+":") {
		t.Errorf("key should start with %q, got %q", cacheVersion+":", a)
	}
}

func TestReadCachedKey_FromHeader(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "out.go")

	wantKey := "v1:abc123"
	contents := "// Code generated by pureast.\n" +
		cacheKeyHeaderLine("// ") + wantKey + "\n" +
		"// pureast-task: something\n" +
		"\npackage foo\n"
	if err := os.WriteFile(path, []byte(contents), 0644); err != nil {
		t.Fatal(err)
	}

	got, ok := readCachedKey(path)
	if !ok {
		t.Fatal("expected cache hit, got miss")
	}
	if got != wantKey {
		t.Errorf("got %q, want %q", got, wantKey)
	}
}

