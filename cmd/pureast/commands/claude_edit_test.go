func TestWriteWithHeader_RoundTrip(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "out.go")

	body := "package foo\n\nfunc X() int { return 1 }\n"
	key := "v1:abcdef"
	task := "test task"

	if err := writeWithHeader(path, task, key, body); err != nil {
		t.Fatal(err)
	}

	got, ok := readCachedKey(path)
	if !ok || got != key {
		t.Errorf("round trip failed: got (%q, %v), want (%q, true)", got, ok, key)
	}

	contents, _ := os.ReadFile(path)
	if !strings.Contains(string(contents), "func X()") {
		t.Errorf("body lost in round-trip; contents:\n%s", contents)
	}
	if !strings.Contains(string(contents), "pureast-task: "+task) {
		t.Errorf("task line missing; contents:\n%s", contents)
	}
}

func TestWriteWithHeader_AtomicReplace(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "out.go")

	// First write
	if err := writeWithHeader(path, "v1", "v1:first", "package a\n"); err != nil {
		t.Fatal(err)
	}
	// Replace
	if err := writeWithHeader(path, "v2", "v1:second", "package b\n"); err != nil {
		t.Fatal(err)
	}

	got, _ := readCachedKey(path)
	if got != "v1:second" {
		t.Errorf("after replace, key = %q, want v1:second", got)
	}
	contents, _ := os.ReadFile(path)
	if !strings.Contains(string(contents), "package b") {
		t.Errorf("expected new body; got:\n%s", contents)
	}
	if strings.Contains(string(contents), "package a") {
		t.Errorf("old body leaked through")
	}
}

